import fs from 'node:fs';
import path from 'node:path';
import {root, loadBrief} from './lib.mjs';

export function registerVideos() {
  const ids = fs.readdirSync(path.join(root, 'src/videos'), {withFileTypes: true}).filter((d) => d.isDirectory()).map((d) => d.name).sort();
  for (const id of ids) {
    loadBrief(id);
    if (!fs.existsSync(path.join(root, 'src/videos', id, 'Video.tsx'))) throw Error(`Missing ${id}/Video.tsx`);
  }
  const code = '// Generated by npm run register. Edit individual video files.\n' +
    ids.map((id, i) => `import {Video as Video${i}} from './videos/${id}/Video';\nimport brief${i} from './videos/${id}/brief.json';`).join('\n') +
    '\nexport const videos = [\n' + ids.map((_, i) => `  {component: Video${i}, brief: brief${i}},`).join('\n') + '\n];\n';
  fs.writeFileSync(path.join(root, 'src/registry.ts'), code);
  console.log(`Registered ${ids.length} video(s): ${ids.join(', ')}`);
  return ids;
}
if (process.argv[1] === new URL(import.meta.url).pathname) registerVideos();
